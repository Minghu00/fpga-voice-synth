def _font(run, cn=SONG, latin=LATIN, size=12, bold=False, color=None):
    run.font.name = latin
    run.font.size = Pt(size)
    run.bold = bold
    rpr = run._element.get_or_add_rPr()
    rf = rpr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts')
        rpr.append(rf)
    rf.set(qn('w:eastAsia'), cn)
    rf.set(qn('w:ascii'), latin)
    rf.set(qn('w:hAnsi'), latin)
    if color:
        run.font.color.rgb = color


def para(text="", size=12, bold=False, cn=SONG, align=None, indent=0.0,
         before=0, after=6, spacing=1.5, color=None, keep=False):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = spacing
    if indent:
        pf.first_line_indent = Pt(size * indent)
    if align is not None:
        p.alignment = align
    pf.keep_with_next = keep
    if text:
        _font(p.add_run(text), cn=cn, size=size, bold=bold, color=color)
    return p


def title(text):
    para(text, size=22, bold=True, cn=HEI, align=WD_ALIGN_PARAGRAPH.CENTER,
         before=0, after=6, spacing=1.4)


def subtitle(text):
    para(text, size=15, cn=HEI, align=WD_ALIGN_PARAGRAPH.CENTER,
         before=0, after=18, spacing=1.4)


def h1(text):
    p = para(text, size=16, bold=True, cn=HEI, before=18, after=8, keep=True)
    return p


def h2(text):
    para(text, size=13.5, bold=True, cn=HEI, before=12, after=6, keep=True)


def h3(text):
    para(text, size=12, bold=True, cn=HEI, before=8, after=4, keep=True)


def body(text, **kw):
    return para(text, size=12, indent=2.0, after=6, **kw)


def bullet(text, size=12, indent_cm=0.0):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before = Pt(0)
    pf.space_after = Pt(4)
    pf.line_spacing = 1.5
    pf.left_indent = Cm(0.74 + indent_cm)
    pf.first_line_indent = Cm(-0.74)
    _font(p.add_run(text), size=size)
    return p


def caption(text):
    para(text, size=10.5, cn=SONG, align=WD_ALIGN_PARAGRAPH.CENTER,
         before=2, after=10, spacing=1.2)


def figure(name, cap, width_cm):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.keep_with_next = True
    p.add_run().add_picture(os.path.join(FIG, name), width=Cm(width_cm))
    caption(cap)


def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    el = OxmlElement('w:shd')
    el.set(qn('w:val'), 'clear')
    el.set(qn('w:color'), 'auto')
    el.set(qn('w:fill'), hexcolor)
    tcPr.append(el)


def set_borders(t, sz=6, color="8EA9C8"):
    tbl = t._tbl
    tblPr = tbl.tblPr
    borders = OxmlElement('w:tblBorders')
    for edge in ('top', 'left', 'bottom', 'right', 'insideH', 'insideV'):
        el = OxmlElement('w:' + edge)
        el.set(qn('w:val'), 'single')
        el.set(qn('w:sz'), str(sz))
        el.set(qn('w:space'), '0')
        el.set(qn('w:color'), color)
        borders.append(el)
    tblPr.append(borders)


def table(headers, rows, widths, align_center=False, size=10.5, caption_text=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    set_borders(t)
    hdr = t.rows[0].cells
    trPr = t.rows[0]._tr.get_or_add_trPr()
    th = OxmlElement('w:tblHeader')
    trPr.append(th)
    for i, h in enumerate(headers):
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(2)
        p.paragraph_format.space_after = Pt(2)
        _font(p.add_run(h), cn=HEI, size=size, bold=True)
        shade(hdr[i], "EAEFF7")
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.space_after = Pt(2)
            p.paragraph_format.line_spacing = 1.15
            if align_center or i > 0:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            _font(p.add_run(str(v)), size=size)
    for r in t.rows:
        for i, c in enumerate(r.cells):
            c.width = Cm(widths[i])
    if caption_text:
        caption(caption_text)
    else:
        para("", size=6, after=4)
    return t


