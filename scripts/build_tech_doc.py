h2("4.1  可扩展之处")
body("本作品在三个方向上留有明确的扩展余地。第一是可验证性：现状已经用测试模式证明了 8 个声部独立工作，"
     "若把触摸模块改配为 16 键模式，复音数可以在不改动振荡器结构的前提下直接翻倍，"
     "因为振荡器本身已经是 32 路独立单元。第二是表情维度：目前缺的是“力度”这一维，"
     "物理原因是电容触摸芯片只有二值输出；若在外挂一颗 I2C 接口的模数转换器并接入压力传感器或"
     "滑动条，就可以把 ADC 数值映射到包络幅度，从而补齐第三个表情维度，改动量约 80 行 RTL。"
     "第三是脱机与联网：底板上现成有一路 WS2812 灯链信号与联阳 BL702 无线模组，"
     "前者可以做脱机曲目指引，后者可以做手机 App 的无线演奏与参数下发，这两条都属于赛题拓展项中"
     "尚未实现的部分。此外，显示页还可以增加“和弦指法提示”“包络参数曲线”等辅助画面，"
     "因为这些图形与音频通路完全解耦，不会影响时序。")

h2("4.2  心得体会")
body("这个项目前后经历了两个阶段：先把“能响”做出来，再把“为什么要这样做”想清楚。"
     "第一阶段里最深的体会是，FPGA 项目的难点往往不在算法，而在“看不见的约定”。"
     "比如触摸芯片的引脚定义在原理图上只是一个网络名，却在实机上决定了模块内部输出脚与输入脚的对应关系，"
     "焊错一根线，仿真全过而板子一声不响；再比如某个按键的上拉电阻在底板上已经存在，"
     "程序却按“未接”去判断电平，结果一上电就静音。这些问题无法靠写代码推理出来，"
     "只能靠对着原理图一根线一根线地核，靠示波器一个信号一个信号地量。")
body("第二阶段体会更深的是“测量比推理可靠”。项目中途出现过一次持续了很久的“两个音按住会颤抖”的问题，"
     "前后给出过五个不同的解释：混音削波、效果模块符号扩展、锁存来回报键、音程差一个全音、"
     "触发算法失效。这五次里有四次修掉的都是真 bug，但没有一次解决用户真正听到的问题。"
     "真正解决问题的转折点，是把 DAC 的数据流直接抓出来做频谱：频谱上只有两根干净谱线，"
     "没有削波、没有样本重复、没有不连续，于是“数字链路有问题”这条线被排除，"
     "问题被重新定义成“两根等幅纯音的拍频，加上一个装不下一个拍的显示窗口”。"
     "从那以后我们形成了一个习惯：先用最少的代码取到原始数据，再谈判断；"
     "任何“我觉得应该是这样”的结论，都要有一条可复现的测量去支撑。")
body("第三个体会关于“取舍”。在 20 736 个 LUT 和 108 MHz 的预算里，"
     "想把波形缓存从 512 加深到 2048，代价是 3 块块存储器和 1.4 MHz 的最高频率，"
     "直接导致时序违例；而把缓存改成 1024 深、16 位宽，只多占 1 块，反而因为顺手删掉了一个跨模块的比较器，"
     "最高频率还涨了。类似的取舍还出现在“滚动显示”和“快照显示”之间："
     "滚动看起来更“实时”，但在每帧消费 804 个采样、缓存只有 1024 深的前提下，"
     "它在数学上就不可能稳。承认这一点、承认有些指标是物理上限，比强行堆资源更专业。")
body("第四个体会是工程化的价值。项目把每一个模块都用 iverilog 建立了独立测试平台，"
     "把每一个指标都写成可以执行的脚本（回归、综合、管脚核对），因此每一次改动都能在十分钟内知道"
     "“有没有把别的地方弄坏”。这套体系在后期救了命：当问题从音频转到显示、又转到时序时，"
     "我们始终有一个绿色的基线可以参考，而不是在一个不断漂移的版本上盲改。")
body("最后一点体会关于沟通。用户听到的是“声音不对”，工程师看到的是“波形不对”，"
     "而真实原因可能既不在声音也不在波形，而在输入侧芯片的一次扫描行为。"
     "把一个模糊的主观描述（“抖”）逐步拆解成可测量的物理量（调幅深度、拍频、"
     "窗口长度、触发点年龄），是这个项目里技术含量最高、也最难速成的部分。")

