// velocity_sense.v  --  力度检测接口（预留，未接入工程，且当前硬件做不到）
//
//  ⚠️ 前提：TTP229 是**二值**输出，芯片只告诉你「这一格被按下了」，
//  拿不到压力 / 接触面积 / 电容变化量。所以这个模块现在**无法实现**，
//  留在这里只是为了把接口先定下来，等硬件方案确定再填。
//
//  ======================== 硬件可选路径 ========================
//  A. FDC2214 / FDC2114 电容数字转换器（I2C，4 通道，28 位分辨率）
//     · 优点：直接给出随手指距离变化的连续量，天然支持力度与「无接触手势」
//     · 代价：要占 2 根 I2C 线 + 需要软件读寄存器（FPGA 里写 I2C 主机）
//     · 覆盖赛题：基础①「≥2 个独立可控维度」+ 拓展②「力度」
//  B. 键盘下方贴 FSR（压阻薄膜）
//     · 优点：模拟量直出，一个 ADC 通道就够；响应线性
//     · 代价：需要 ADC（Dock 上没有，得外接模块），且要机械改造
//  C. STM32/ESP32 读 TTP229 后再推算「按下时长 → 力度」
//     · 优点：零硬件改动
//     · 缺点：**这不是真力度**，只是包络预设切换。答辩时会被问穿，
//       只能叫「触键速率敏感」，不能叫力度感应。不建议作为主要论据。
//
//  ======================== 接口约定 ========================
//  本模块的职责单一：把任意一种模拟量输入，归一化并去抖成 VOICES 路
//  8 位力度，再交给 keymap8 / osc_bank 去映射到包络峰值或滤波器截止。
//
//  注意力度应当**乘到包络峰值上**，而不是乘到相位增量上：
//      adsr 的 SUSTAIN 是参数，改它需要重配置；更简单的做法是
//      在 mixer16 之前乘 env（env_out = env * vel >> 8）。
//
//  当前状态：骨架。输出全 0x80（中性值），未被工程引用。
//=============================================================================
`timescale 1ns / 1ps

module velocity_sense #(
    parameter integer VOICES = 8,
    parameter integer SMOOTH = 64        // 一阶低通系数，越大越平滑
)(
    input  wire                  clk,
    input  wire                  rst_n,
    input  wire                  en,        // 一 clk 脉冲/样本（fs）
    input  wire [11:0]           adc_raw,   // 来自 ADC / FDC2214 的原始值
    input  wire [VOICES-1:0]     key_down,  // 哪些键当前按下
    output reg  [8*VOICES-1:0]   vel        // 每声部 0..255，中性 128
);

    // TODO: 接入时实现。
    //   1) adc_raw 做一阶 IIR 平滑
    //   2) key_down 的上升沿瞬间锁存当时的平滑值作为该声部力度
    //      （按键按下那一刻的接触速度/面积才是"力度"，按住后变化不该改音量）
    //   3) 归一化到 0..255，下限钳到 32（避免完全听不见）
    //
    // 中性值占位，保证文件可编译：
    integer i;
    always @(posedge clk) begin
        if (!rst_n) begin
            for (i = 0; i < VOICES; i = i + 1)
                vel[i*8 +: 8] <= 8'd128;
        end else begin
            for (i = 0; i < VOICES; i = i + 1)
                vel[i*8 +: 8] <= 8'd128;
        end
    end

endmodule
