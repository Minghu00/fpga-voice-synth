h3("（1）输入处理与音符映射")
body("ttp229_rx 每 512 kHz 拉一次串行时钟，把 16 位键位图移入寄存器，两级同步消除亚稳态，"
     "再用 20 ms 的“持续被报告”判据把机械/电容抖动滤掉。keymap8 把键位图直接映射成 8 个门控信号与"
     "8 个音高索引，索引查表得到 32 位频率控制字；它同时实现锁存模式（逐格点选、叠加成和弦）"
     "与音量键的边沿检测。")

h3("（2）32 路振荡器")
body("振荡器是“复音数”与“吞吐量”的来源。osc_bank 内维护 reg [31:0] phase [0:31]，即 32 个独立的 32 位相位累加器；"
     "每路的频率字由 inc_lut 给出，四个加法分量分别是基频的 1、2、3、4 倍，在波表模式下各自读取"
     "一张独立的 4096 点波表。振荡器在帧内按槽位串行推进，但每路的状态完全独立寄存，"
     "因此 32 个发声单元是真实的 32 个，而不是一个单元分时借用。")
body("音高精度取决于 32 位累加器的截断长度：频率字 = 频率 × 2³² / 采样率，本作品对 25 个音名逐项计算并"
     "取整，实测偏差远小于 1 音分，在示波器与频谱上均不可察觉。")

h3("（3）包络")
body("adsr 为每个声部维护一个 16 位包络值，状态机分为空闲、起音、衰减、保持、释放五态，"
     "只在 sample_tick 时推进一次，因此包络的每一个台阶都精确对应一个采样点。默认参数下起音约 4 ms、"
     "衰减到保持电平后维持，释放约 226 ms；释放期间重新按下会回到起音态，保证连奏不吞音。")

h3("（4）混音、音量与限幅")
body("mixer16 把 8 个声部逐帧相加。为了既省资源又保留立体声成像，它按声部奇偶把累加器拆成两路，"
     "每帧只对两个部分和各做一次 13/16 乘法得到左右声道，最后的单声道输出再做一次 3 位右移完成 8 声部归一化。"
     "audio_out 提供 16 档 13 位 Q8 增益（0.5× 至 16×），并在 3/4 满刻度处接入斜率 1/8 的软拐点限幅器："
     "多音叠加时不再硬削成方波，而是把峰值平滑地压进 16 位范围。")

h3("（5）I2S 输出")
